CRISIS_NUDGE = """[Система: в последнем сообщении человека есть признаки острого состояния или мыслей о самоповреждении.
Ответь особенно бережно, признай его боль, не переводи тему и не давай инструкций.
Прямо скажи, что важно не оставаться одному и связаться с живым человеком или службой помощи (112, горячая линия).
Останься коротким и тёплым.]"""


def context_note(mood: int | None, feelings: list[str], topic: str | None) -> str | None:
    """Короткая заметка для модели о том, что человек отметил сам.

    Модель не должна пересказывать её человеку — только учитывать.
    """
    parts = []
    if mood is not None:
        parts.append(f"настроение {mood} из 5 (1 — очень плохо, 5 — хорошо)")
    if feelings:
        parts.append("чувства: " + ", ".join(feelings))
    if topic:
        parts.append(f"с чем пришёл: {topic}")
    if not parts:
        return None
    return (
        "[Система: человек сам отметил перед разговором — "
        + "; ".join(parts)
        + ". Учитывай это мягко, не пересказывай и не ставь ярлыков.]"
    )


